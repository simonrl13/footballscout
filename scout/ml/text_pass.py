"""Pre-registered Wikipedia text-feature pass (docs/RESEARCH_LOG.md, 2026-10-12). Validation data only.

Protocol (identical to the stats pass, scout/ml/feature_pass.py): B0 vs B0+C (contract) vs B0+C+M (contract + moves);
LightGBM with the fixed tuned settings and ridge (alpha from best_params.json); rolling-origin CV (fit 2013..y-1, score
y, y = 2016-2021) plus validation 2022 (fit 2013-2021). A set helps if its mean CV MAE (LightGBM) beats B0's and the
paired-bootstrap 95% CI of MAE(set) - MAE(B0), pooled over the CV folds + 2022, lies entirely below 0. Winner: the
helping set with the lowest mean CV MAE, else B0. Injury counts are reported, never used as a feature.

Usage: uv run --env-file .env python -m scout.ml.text_pass      -> reports/m3a_text_pass.md, MLflow run
"""
import pandas as pd

from scout.ml.feature_pass import evaluate
from scout.ml.train import ROOT, TEST_YEARS, TRAIN_YEARS, VAL_YEAR, git_commit, md_table
from scout.text.wiki_features import CONTRACT, MOVES, REPORTED, build_wiki_features, load_signals

REPORT = ROOT / "reports" / "m3a_text_pass.md"
CANDIDATES = {"B0": [], "B0+C": CONTRACT, "B0+C+M": CONTRACT + MOVES}
PREREGISTERED = "see docs/RESEARCH_LOG.md, 2026-10-12 PRE-REGISTRATION: Wikipedia text features"


def dataset() -> pd.DataFrame:
    from scout.data.raw import read_raw
    from scout.data.snapshots import build_snapshots
    from scout.ml.features import build_features
    from scout.text import store
    raw = read_raw()
    s = build_snapshots(raw, years=TRAIN_YEARS + [VAL_YEAR])
    f = build_features(s, raw)
    with store.connect() as conn:
        signals = load_signals(conn)
    w = build_wiki_features(s, signals)
    df = pd.concat([s.drop(columns=[c for c in f.columns if c in s.columns]), f, w], axis=1)
    df = df[df.target.notna()]
    assert not df.year.isin(TEST_YEARS).any()
    return df


def main() -> None:
    import mlflow
    from scout.ml.tracking import start_run
    df = dataset()
    coverage = df.groupby("year").agg(snapshots=("contract_known", "size"), contract_known=("contract_known", "mean"),
                                      **{c: (c, "mean") for c in ["contract_ext_12m", "text_transfers_12m",
                                                                  "text_loans_12m"] + REPORTED}).round(3)
    with start_run("text-feature-pass", tags={"stage": "m3a", "preregistered": "2026-10-12"}):
        table, comp, winner, n = evaluate(df, CANDIDATES)
        mlflow.log_param("winner", winner)
        for name, r in comp.iterrows():
            mlflow.log_metric(f"cv_mae_{name.replace('+', '_plus_')}", float(r["mean CV MAE"]))
            mlflow.log_metric(f"val_mae_{name.replace('+', '_plus_')}", float(r["val MAE 2022"]))
    lines = [
        "# M3a Wikipedia text-feature pass (auto-generated by `python -m scout.ml.text_pass`)", "",
        f"Pre-registered ({PREREGISTERED}). Run at commit `{git_commit()}`. Validation data only (2013–2022 snapshots; the "
        f"test years are never loaded). Pooled CV folds 2016–2021 + validation 2022: n = {n:,}.", "",
        f"**Decision (pre-registered rule): baseline = `{winner}`.**", "",
        "## LightGBM: each set vs B0 (decides) and vs ridge (reported)", "",
        "`vs B0` = MAE(set) − MAE(B0) on the pooled folds, with a paired-bootstrap 95% CI; negative = better.", "",
        md_table(comp, fmt="{:.4f}"), "",
        "## All MAEs (LightGBM and ridge, per fold)", "", md_table(table.set_index("set"), fmt="{:.4f}"), "",
        "## Coverage by snapshot year (means over labelled snapshots; injuries reported only)", "", md_table(coverage), "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT}; winner = {winner}")


if __name__ == "__main__":
    main()
